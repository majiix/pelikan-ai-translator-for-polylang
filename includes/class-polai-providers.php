	/**
	 * Get a single provider definition by ID.
	 *
	 * @param string $provider_id Provider identifier.
	 * @return array<string, mixed>|null
	 */
	public static function get( $provider_id ) {
		$providers = self::get_all();
		return isset( $providers[ $provider_id ] ) ? $providers[ $provider_id ] : null;
	}

	/**
	 * Check whether a provider ID is registered.
	 *
	 * @param string $provider_id Provider identifier.
	 * @return bool
	 */
	public static function exists( $provider_id ) {
		$providers = self::get_all();
		return isset( $providers[ $provider_id ] );
	}

	/**
	 * Build lightweight provider metadata for client-side scripts.
	 *
	 * @return array<string, array<string, mixed>>
	 */
	public static function get_client_meta() {
		$meta = array();
		foreach ( self::get_all() as $id => $provider ) {
			$meta[ $id ] = array(
				'id'                  => $id,
				'name'                => $provider['name'],
				'public_models'       => ! empty( $provider['public_models'] ),
				'can_fetch_models'    => ! empty( $provider['models_url'] ) || ! empty( $provider['requires_base_url'] ),
				'docs_url'            => $provider['docs_url'],
				'requires_key'        => ! empty( $provider['requires_key'] ),
				'requires_account_id' => ! empty( $provider['requires_account_id'] ),
				'account_id_label'    => $provider['account_id_label'],
				'requires_base_url'   => ! empty( $provider['requires_base_url'] ),
				'default_model'       => $provider['default_model'],
				'preset_models'       => $provider['preset_models'],
			);
		}
		return $meta;
	}
